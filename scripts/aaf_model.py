#!/usr/bin/env python3
"""Bake the AAF object model (the classes, properties and types an AAF file's
meta dictionary declares) into Rust.

    uv run --no-project --with pyaaf2==1.7.1 python -I scripts/aaf_model.py [out.rs]
    cargo fmt

The model is the AAF Object Specification's (AMWA, SMPTE-registered labels)
together with the Avid extensions every Avid application writes, as pyaaf2
(MIT, github.com/markreidvfx/pyaaf2) tabulates them. pyaaf2 builds its meta
dictionary in memory exactly as it writes it into new files (dynamic local
property ids included); this script reads that dictionary and writes
crates/faderframe-aaf/src/model/baseline.rs (or the path given), then
`cargo fmt` formats it. Regenerate, never edit.
"""

import io
import pathlib
import sys

import aaf2
from aaf2 import types

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "faderframe-aaf" / "src" / "model" / "baseline.rs"


def auid(a):
    h = str(a.uuid if hasattr(a, "uuid") else a).replace("-", "")
    return f"id(0x{h[0:8]}_{h[8:12]}_{h[12:16]}_{h[16:20]}_{h[20:32]})"


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def typedef_kind(t):
    if isinstance(t, types.TypeDefInt):
        return f"TypeKind::Int {{ size: {t.size}, signed: {'true' if t.signed else 'false'} }}"
    if isinstance(t, types.TypeDefExtEnum):
        items = ", ".join(f"({text(n)}, {auid(v)})" for v, n in t.elements.items())
        return f"TypeKind::ExtEnum {{ items: &[{items}] }}"
    if isinstance(t, types.TypeDefEnum):
        items = ", ".join(f"({text(n)}, {v})" for v, n in t.elements.items())
        return (
            f"TypeKind::Enum {{ element: {auid(t.element_typedef.auid)}, items: &[{items}] }}"
        )
    if isinstance(t, types.TypeDefRecord):
        names = t.member_names
        members = ", ".join(
            f"({text(n)}, {auid(m.auid)})" for n, m in zip(names, t.member_types.value)
        )
        return f"TypeKind::Record {{ members: &[{members}] }}"
    if isinstance(t, types.TypeDefFixedArray):
        return (
            f"TypeKind::FixedArray {{ element: {auid(t.element_typedef.auid)}, count: {t.size} }}"
        )
    if isinstance(t, types.TypeDefVarArray):
        return f"TypeKind::VarArray {{ element: {auid(t.element_typedef.auid)} }}"
    if isinstance(t, types.TypeDefSet):
        return f"TypeKind::Set {{ element: {auid(t.element_typedef.auid)} }}"
    if isinstance(t, types.TypeDefRename):
        return f"TypeKind::Rename {{ of: {auid(t.renamed_typedef.auid)} }}"
    if isinstance(t, types.TypeDefString):
        return f"TypeKind::String {{ element: {auid(t.element_typedef.auid)} }}"
    if isinstance(t, types.TypeDefStream):
        return "TypeKind::Stream"
    if isinstance(t, types.TypeDefOpaque):
        return "TypeKind::Opaque"
    if isinstance(t, types.TypeDefIndirect):
        return "TypeKind::Indirect"
    if isinstance(t, types.TypeDefGenericCharacter):
        classdef = t.root.metadict.lookup_classdef(t.class_id)
        pid = next(
            p.pid
            for p in classdef.all_propertydefs()
            if str(p.auid) == "0e040101-0101-0111-060e-2b3401010101"
        )
        return f"TypeKind::GenericCharacter {{ size: {t.size}, pid: 0x{pid:04x} }}"
    if isinstance(t, types.TypeDefCharacter):
        return "TypeKind::Character"
    if isinstance(t, types.TypeDefStrongRef):
        return f"TypeKind::StrongRef {{ class: {auid(t.ref_classdef.auid)} }}"
    if isinstance(t, types.TypeDefWeakRef):
        path = ", ".join(auid(a) for a in t.target_set_path)
        return f"TypeKind::WeakRef {{ class: {auid(t.ref_classdef.auid)}, path: &[{path}] }}"
    raise ValueError(f"unknown type definition {t!r}")


def main():
    f = aaf2.file.AAFFile(None, "w")
    meta = f.metadict
    out = io.StringIO()
    w = out.write
    w("// Generated by scripts/aaf_model.py from pyaaf2 1.7.1 (MIT); regenerate, never edit.\n")
    w("// The AAF object model (AMWA AAF Object Specification) and Avid's extensions,\n")
    w("// as an AAF file's meta dictionary declares them.\n\n")
    w("use super::{ClassDef, PropDef, TypeDef, TypeKind};\n")
    w("use crate::ids::id;\n\n")
    w("pub(crate) static CLASSES: &[ClassDef] = &[\n")
    root_class = meta.lookup_classdef("Root")
    classes = [root_class] + list(meta["ClassDefinitions"].values())
    for c in classes:
        parent = c.parent_id or c.auid
        w(f"    ClassDef {{\n        name: {text(c.class_name)},\n        id: {auid(c.auid)},\n")
        w(f"        parent: {auid(parent)},\n        concrete: {'true' if c.concrete else 'false'},\n")
        w("        props: &[\n")
        for p in c.propertydefs:
            w(
                f"            PropDef {{ name: {text(p.property_name)}, id: {auid(p.auid)}, "
                f"pid: 0x{p.pid:04x}, ty: {auid(p.typedef_id)}, "
                f"optional: {'true' if p.optional else 'false'}, "
                f"unique: {'true' if p.unique else 'false'} }},\n"
            )
        w("        ],\n    },\n")
    w("];\n\n")
    w("pub(crate) static TYPES: &[TypeDef] = &[\n")
    for t in meta["TypeDefinitions"].values():
        w(f"    TypeDef {{ name: {text(t.type_name)}, id: {auid(t.auid)}, kind: {typedef_kind(t)} }},\n")
    w("];\n")
    dest = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(out.getvalue())
    print(f"wrote {dest} ({len(classes)} classes, {len(meta['TypeDefinitions'])} types)")


if __name__ == "__main__":
    sys.exit(main())
