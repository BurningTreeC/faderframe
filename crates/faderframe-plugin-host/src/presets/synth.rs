//! Synth patches: the first fifteen (leads, pads, keys, plucks, basses and
//! an effect) at the top of the menu, then the second wave's in groups
//! (Bass, Leads, Pads, Keys, Plucks, FX), each showing off what came with
//! it: the ladder and notch filters, sync, ring and FM, the second LFO,
//! the mod envelope and the matrix, drift, and the effects.
//!
//! Levelled by `the_synth_presets_are_balanced` (played as meant, each
//! peaks at −18 LUFS momentary).

use super::{FactoryPreset, preset};

pub(super) fn synth() -> Vec<FactoryPreset> {
    let mut all = first_wave();
    all.extend(second_wave());
    all
}

