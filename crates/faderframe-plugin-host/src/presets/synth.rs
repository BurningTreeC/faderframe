/// A matrix slot: `(source, target, amount)`.
fn route(slot: usize, source: usize, target: usize, amount: f64) -> [(u32, f64); 3] {
    use crate::devices::synth::id;
    [
        (id::mod_source(slot), source as f64),
        (id::mod_target(slot), target as f64),
        (id::mod_amount(slot), amount),
    ]
}

/// A preset from its settings and matrix routes, in a group.
fn patch(
    name: &'static str,
    group: &'static str,
    set: &[(u32, f64)],
    routes: &[[(u32, f64); 3]],
) -> FactoryPreset {
    let mut all = set.to_vec();
    for r in routes {
        all.extend_from_slice(r);
    }
    preset(name, &all).in_group(group)
}

