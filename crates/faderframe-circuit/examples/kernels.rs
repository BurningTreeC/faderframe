//! Compiles the reduced LU kernels in `src/dsp/partition/kernels.rs`.
//!
//! A kernel is `solve_masked_planned` (reciprocal pivots) unrolled for one
//! sparsity pattern and one pivot plan: the same swaps, reciprocal pivots,
//! soundness and finiteness checks and multiply-subtracts in the same order,
//! on constant indices (see `Kernel` in `partition.rs`), about three times
//! faster than the masked replay. Which ones to compile comes from a census:
//! the preamps and console buses run at three rates, through their Gain (or
//! Drive) and on six signals with `kernel_census` on, and every (pattern,
//! plan) they replay that no kernel covers yet is added, the most solved
//! first, until `COVERAGE` of each system's solves have one. The plans move
//! with the operating point -- the German 76 at full gain replays over three
//! hundred -- so the census drives each model hard. The kernels already in
//! the table (upstream's, the guitar voices' among them) are kept and
//! regenerated as they were.
//!
//! `cargo run --release -p faderframe-circuit --example kernels` rewrites the
//! file; `-- --check` only checks that the file is what this would write from
//! its own table (no census).
use faderframe_circuit::dsp::partition::kernel_census;
use faderframe_circuit::preamp::{Preamp, CONSOLE_BUSES, MODELS};
use std::collections::HashMap;
use std::fmt::Write as _;

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/src/dsp/partition/kernels.rs");

/// The share of each system's solves the kernels should cover.
const COVERAGE: f64 = 0.995;

/// Fewer census solves than this are not worth a kernel.
const MIN_SOLVES: u64 = 200;

const HEADER: &str = "//! Generated by `cargo run --release --example kernels`. Do not edit.
//!
//! Each kernel is `solve_masked_planned` unrolled for one pattern and one
//! pivot plan; see `Kernel` in `partition.rs`.
#![allow(clippy::all)]
use super::{Bail, Kernel};
";

#[derive(Clone, PartialEq)]
struct Entry {
    index: usize,
    plan: Vec<u8>,
    pattern: Vec<u64>,
}

fn main() {
    let text = std::fs::read_to_string(PATH).expect("kernels.rs");
    let mut entries = parse_table(&text);
    if std::env::args().any(|a| a == "--check") {
        let same = render(&entries) == text;
        println!(
            "{} kernels; the file {} what this writes",
            entries.len(),
            if same { "is" } else { "is NOT" }
        );
        std::process::exit(if same { 0 } else { 1 });
    }
    let census = census();
    let added = select(&census, &mut entries);
    std::fs::write(PATH, render(&entries)).expect("write kernels.rs");
    let widest = census
        .keys()
        .map(|(pattern, _)| entries.iter().filter(|e| covers(e, pattern)).count())
        .max()
        .unwrap_or(0);
    println!(
        "{} kernels ({added} new); at most {widest} cover one pattern (KERNEL_CANDIDATES must be at least that)",
        entries.len()
    );
}

/// The table at the end of the file.
fn parse_table(text: &str) -> Vec<Entry> {
    let numbers = |s: &str| -> Vec<u64> {
        s.split(',')
            .map(|x| x.trim().parse().expect("a number"))
            .collect()
    };
    text.lines()
        .filter_map(|line| line.strip_prefix("    Kernel { plan: &["))
        .map(|rest| {
            let (plan, rest) = rest.split_once("], pattern: &[").expect("pattern");
            let (pattern, rest) = rest.split_once("], run: kernel_").expect("run");
            let index = rest.trim_end_matches(" },").parse().expect("index");
            Entry {
                index,
                plan: numbers(plan).into_iter().map(|p| p as u8).collect(),
                pattern: numbers(pattern),
            }
        })
        .collect()
}

/// Whether kernel `e` serves a system with `pattern` replaying its plan.
fn covers(e: &Entry, pattern: &[u64]) -> bool {
    e.pattern.len() == pattern.len()
        && e.pattern
            .iter()
            .zip(pattern)
            .all(|(&have, &need)| need & !have == 0)
}

/// Every (pattern, plan) the preamps and buses replay, with its solves.
fn census() -> HashMap<(Vec<u64>, Vec<u8>), u64> {
    kernel_census::enable();
    let mut total = HashMap::new();
    for rate in [44_100.0, 48_000.0, 96_000.0] {
        let signals = signals(rate);
        for model in 0..MODELS + CONSOLE_BUSES {
            let settings: Vec<(f64, bool)> = if model >= MODELS {
                [-12.0, -6.0, 0.0, 6.0, 12.0]
                    .iter()
                    .map(|&drive| (drive, false))
                    .collect()
            } else {
                let gains = [0.0, 0.1, 0.25, 0.4, 0.5, 0.6, 0.75, 0.9, 1.0];
                let lines: &[bool] = if model == 0 { &[false, true] } else { &[false] };
                lines
                    .iter()
                    .flat_map(|&bridging| gains.iter().map(move |&g| (g, bridging)))
                    .collect()
            };
            for &(gain, bridging) in &settings {
                for signal in &signals {
                    let mut p = Preamp::with_line(model, rate, gain, 0.0, bridging).expect("model");
                    for &x in signal {
                        std::hint::black_box(p.process(x));
                    }
                    for (pattern, plan, count) in kernel_census::take() {
                        *total.entry((pattern, plan)).or_insert(0) += count;
                    }
                }
            }
            eprintln!("{rate} Hz, model {model}: {} systems so far", total.len());
        }
    }
    total
}

/// What the census plays: a drum loop near full scale, the four-tone chord
/// at two levels, and sines low, high and at full scale.
fn signals(rate: f64) -> Vec<Vec<f64>> {
    let second = rate as usize;
    let tau = std::f64::consts::TAU;
    let tone = |f: f64, db: f64, n: usize| -> Vec<f64> {
        let a = 10f64.powf(db / 20.0);
        (0..n)
            .map(|i| a * (tau * f * i as f64 / rate).sin())
            .collect()
    };
    let chord = |db: f64, n: usize| -> Vec<f64> {
        let a = 10f64.powf(db / 20.0);
        (0..n)
            .map(|i| {
                let t = i as f64 / rate;
                let env = (-(t % 0.25) * 12.0).exp();
                let x = [110.0, 277.2, 330.0, 880.0]
                    .iter()
                    .map(|f| (tau * f * t).sin())
                    .sum::<f64>();
                a * env * x / 4.0
            })
            .collect()
    };
    vec![
        drums(rate, 2 * second),
        chord(-18.0, second),
        chord(-6.0, second),
        tone(10_000.0, -18.0, second / 2),
        tone(100.0, -6.0, second / 2),
        tone(1_000.0, 0.0, second / 2),
    ]
}

/// Kick, snare and hats at 112 BPM, peaking near -3 dBFS.
fn drums(rate: f64, n: usize) -> Vec<f64> {
    let tau = std::f64::consts::TAU;
    let eighth = (rate * 60.0 / 112.0 / 2.0) as usize;
    let mut seed = 0x2545_f491_4f6c_dd1du64;
    let mut noise = move || {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        (seed >> 11) as f64 / (1u64 << 53) as f64 * 2.0 - 1.0
    };
    let mut last = 0.0;
    (0..n)
        .map(|i| {
            let step = i / eighth;
            let t = (i % eighth) as f64 / rate;
            let white = noise();
            let hat = 0.15 * (white - last) * (-t / 0.03).exp();
            last = white;
            let beat = match step % 8 {
                0 | 4 => {
                    let f = 45.0 + 60.0 * (-t / 0.05).exp();
                    0.6 * (tau * f * t).sin() * (-t / 0.25).exp()
                }
                2 | 6 => (0.25 * white + 0.2 * (tau * 180.0 * t).sin()) * (-t / 0.12).exp(),
                _ => 0.0,
            };
            beat + hat
        })
        .collect()
}

/// Adds kernels for the census's uncovered systems; returns how many.
fn select(census: &HashMap<(Vec<u64>, Vec<u8>), u64>, entries: &mut Vec<Entry>) -> usize {
    let mut by_pattern: HashMap<&Vec<u64>, Vec<(&Vec<u8>, u64)>> = HashMap::new();
    for ((pattern, plan), &count) in census {
        by_pattern.entry(pattern).or_default().push((plan, count));
    }
    let mut patterns: Vec<_> = by_pattern.into_iter().collect();
    patterns.sort_by(|a, b| a.0.cmp(b.0));
    let mut added = 0;
    for (pattern, mut plans) in patterns {
        plans.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(b.0)));
        let total: u64 = plans.iter().map(|p| p.1).sum();
        let compiled = |entries: &[Entry], plan: &[u8]| {
            entries
                .iter()
                .any(|e| e.plan.as_slice() == plan && covers(e, pattern))
        };
        let mut served: u64 = plans
            .iter()
            .filter(|(plan, _)| compiled(entries, plan))
            .map(|p| p.1)
            .sum();
        for &(plan, count) in &plans {
            if served as f64 >= COVERAGE * total as f64 || count < MIN_SOLVES {
                break;
            }
            if compiled(entries, plan) {
                continue;
            }
            entries.push(Entry {
                index: entries.len(),
                plan: plan.clone(),
                pattern: pattern.clone(),
            });
            served += count;
            added += 1;
        }
    }
    added
}

/// The whole file for `entries`.
fn render(entries: &[Entry]) -> String {
    let mut out = String::from(HEADER);
    for e in entries {
        out.push('\n');
        kernel(&mut out, e);
    }
    out.push_str("\npub(super) static KERNELS: &[Kernel] = &[\n");
    for e in entries {
        let plan: Vec<String> = e.plan.iter().map(u8::to_string).collect();
        let pattern: Vec<String> = e.pattern.iter().map(u64::to_string).collect();
        let _ = writeln!(
            out,
            "    Kernel {{ plan: &[{}], pattern: &[{}], run: kernel_{} }},",
            plan.join(", "),
            pattern.join(", "),
            e.index
        );
    }
    out.push_str("];\n");
    out
}

/// Columns of `mask` from `start` on, ascending.
fn bits(mask: u64, start: usize, n: usize) -> impl Iterator<Item = usize> {
    (start..n).filter(move |&j| (mask >> j) & 1 == 1)
}

/// One kernel: `solve_masked_planned`'s elimination and back substitution,
/// its masks followed at generation time instead of at run time.
fn kernel(out: &mut String, e: &Entry) {
    let n = e.plan.len();
    let mut mask = e.pattern.clone();
    let _ = writeln!(
        out,
        "fn kernel_{}(m: &mut [f64], r: &mut [f64], sound: &mut bool) -> Result<(), Bail> {{",
        e.index
    );
    let _ = writeln!(
        out,
        "    let Ok(m) = <&mut [f64; {}]>::try_from(m) else {{ return Err(Bail::Tail(0)); }};",
        n * n
    );
    let _ = writeln!(
        out,
        "    let Some(Ok(r)) = r.get_mut(..{n}).map(<&mut [f64; {n}]>::try_from) else {{ return Err(Bail::Tail(0)); }};"
    );
    for column in 0..n {
        let pivot = e.plan[column] as usize;
        assert!(column <= pivot && pivot < n, "a plan entry out of range");
        if pivot != column {
            for j in bits(mask[column] | mask[pivot], column, n) {
                let _ = writeln!(out, "    m.swap({}, {});", column * n + j, pivot * n + j);
            }
            let _ = writeln!(out, "    r.swap({column}, {pivot});");
            mask.swap(column, pivot);
        }
        let diagonal = column * n + column;
        let _ = writeln!(out, "    let d = m[{diagonal}];");
        let _ = writeln!(
            out,
            "    if d.abs() < 1e-30 || !d.is_finite() {{ return Err(Bail::Tail({column})); }}"
        );
        out.push_str("    let inv = 1.0 / d;\n");
        let _ = writeln!(out, "    m[{diagonal}] = inv;");
        let rows: Vec<usize> = (column + 1..n)
            .filter(|&row| (mask[row] >> column) & 1 == 1)
            .collect();
        if !rows.is_empty() {
            out.push_str("    let ceiling = d.abs() * 16.0;\n");
            let _ = writeln!(out, "    let pr = r[{column}];");
        }
        let upper: Vec<usize> = bits(mask[column], column + 1, n).collect();
        let upper_mask = upper.iter().fold(0u64, |m, &j| m | 1 << j);
        for row in rows {
            let _ = writeln!(out, "    let e = m[{}];", row * n + column);
            out.push_str("    if e.abs() > ceiling { *sound = false; }\n");
            out.push_str("    let f = e * inv;\n");
            for &j in &upper {
                let _ = writeln!(out, "    m[{}] -= f * m[{}];", row * n + j, column * n + j);
            }
            let _ = writeln!(out, "    r[{row}] -= f * pr;");
            mask[row] |= upper_mask;
        }
    }
    for row in (0..n).rev() {
        let upper: Vec<usize> = bits(mask[row], row + 1, n).collect();
        if upper.is_empty() {
            let _ = writeln!(out, "    let v = r[{row}];");
        } else {
            let _ = writeln!(out, "    let mut v = r[{row}];");
            for j in upper {
                let _ = writeln!(out, "    v -= m[{}] * r[{j}];", row * n + j);
            }
        }
        let _ = writeln!(out, "    let d = m[{}];", row * n + row);
        out.push_str("    if !d.is_finite() || d == 0.0 { return Err(Bail::Failed); }\n");
        out.push_str("    let x = v * d;\n");
        let _ = writeln!(out, "    r[{row}] = x;");
        out.push_str("    if !x.is_finite() { return Err(Bail::Failed); }\n");
    }
    out.push_str("    Ok(())\n}\n");
}
